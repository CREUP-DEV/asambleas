import type { MemberRef } from "../../../shared/types/api";

/**
 * Who has the working draft of a document open in the editor, kept in this
 * process's memory (no table, no history): each open editor sends a
 * heartbeat (POST .../documents/[document]/presence) and drops out when it
 * leaves or stops beating for PRESENCE_TTL_MS. Production runs one app
 * container, so one process sees every editor; after a restart the list
 * fills again within one heartbeat.
 *
 * Entries are keyed by account and browser tab, never by account alone: a
 * council's account is shared by several people, and two of them on the same
 * draft are exactly the case to tell apart.
 */

/**
 * The client beats every 20 s, but browsers slow the timers of a tab left
 * in the background to one a minute: 90 s keeps such an editor listed. A tab
 * that closes says goodbye at once (`leaving`); this only covers the rest.
 */
export const PRESENCE_TTL_MS = 90_000;
/** Open editors kept per document; the least recently seen go first. */
export const MAX_EDITORS_PER_DOCUMENT = 50;
/** Documents tracked at once; past it, expired ones are swept first. */
export const MAX_DOCUMENTS = 2_000;

export interface PresenceKey {
  userId: string;
  /** Random id of the browser tab, generated by the client. */
  tabId: string;
}

export interface PresenceEntry extends PresenceKey {
  /** The intranet's name, else the Google one (as in the history). */
  name: string;
  /** The member the account acts for, if any. */
  member: MemberRef | null;
  /** The editor holds changes it has not saved yet. */
  unsaved: boolean;
  /** First heartbeat of this tab (ms). */
  since: number;
  /** Latest heartbeat (ms). */
  seenAt: number;
}

const store = new Map<string, Map<string, PresenceEntry>>();

const entryKey = (key: PresenceKey) => `${key.userId}\u0000${key.tabId}`;

function pruneDocument(documentId: string, now: number): void {
  const editors = store.get(documentId);
  if (!editors) return;
  for (const [key, entry] of editors) {
    if (now - entry.seenAt > PRESENCE_TTL_MS) editors.delete(key);
  }
  if (editors.size === 0) store.delete(documentId);
}

function sweep(now: number): void {
  for (const documentId of [...store.keys()]) pruneDocument(documentId, now);
}

/** Records a heartbeat of one editor tab. */
export function touchPresence(
  documentId: string,
  entry: Omit<PresenceEntry, "since" | "seenAt">,
  now: number = Date.now(),
): void {
  pruneDocument(documentId, now);
  let editors = store.get(documentId);
  if (!editors) {
    if (store.size >= MAX_DOCUMENTS) sweep(now);
    // Still full of live editors: this one goes unannounced, nothing breaks.
    if (store.size >= MAX_DOCUMENTS) return;
    editors = new Map();
    store.set(documentId, editors);
  }
  const key = entryKey(entry);
  const previous = editors.get(key);
  editors.set(key, {
    userId: entry.userId,
    tabId: entry.tabId,
    name: entry.name,
    member: entry.member,
    unsaved: entry.unsaved,
    since: previous?.since ?? now,
    seenAt: now,
  });
  if (editors.size > MAX_EDITORS_PER_DOCUMENT) {
    const oldest = [...editors.entries()]
      .sort((a, b) => a[1].seenAt - b[1].seenAt)
      .slice(0, editors.size - MAX_EDITORS_PER_DOCUMENT);
    for (const [stale] of oldest) editors.delete(stale);
  }
}

/** Drops one editor tab (it closed the editor). Only its own account can. */
export function leavePresence(documentId: string, key: PresenceKey): void {
  const editors = store.get(documentId);
  if (!editors) return;
  editors.delete(entryKey(key));
  if (editors.size === 0) store.delete(documentId);
}

/**
 * The editor tabs open on a document, except the caller's own tab, in the
 * order they opened it.
 */
export function listPresence(
  documentId: string,
  self: PresenceKey,
  now: number = Date.now(),
): PresenceEntry[] {
  pruneDocument(documentId, now);
  const own = entryKey(self);
  return [...(store.get(documentId)?.entries() ?? [])]
    .filter(([key]) => key !== own)
    .map(([, entry]) => entry)
    .sort((a, b) => a.since - b.since);
}

/** For tests. */
export function resetPresence(): void {
  store.clear();
}
