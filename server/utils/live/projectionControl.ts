/**
 * Which session console controls the projection (user's decision of
 * 2026-11-19): one browser tab of the Mesa at a time decides what is on
 * screen (the item, document, amendment or vote in debate, the scroll, the
 * pointer, the live tally); every other open console works on its own and
 * records without projecting. Kept in this process's memory, like the
 * editors' presence (presence.ts): production runs one app container, and
 * after a restart the first console to beat takes control again.
 *
 * Consoles are keyed by account and browser tab, never by account alone:
 * two people on one Mesa account are two consoles. Each open console beats
 * (POST .../projection-control); one silent for CONTROL_TTL_MS drops out. A
 * console that closes says so (`leave`): the holder keeps control for
 * CONTROL_GRACE_MS, so a reload of the same tab (same tab id) keeps it, and
 * only then does control pass on. Control passes to the console open
 * longest; anyone may take it at any time.
 *
 * Who holds control changes only in beatConsole, takeControl and
 * leaveConsole; isController only reads. A change is recorded in the
 * session's history by the console that receives control (`announce`), at
 * its own call: taken at once, handed on or first at its next beat, so the
 * event always names who holds control.
 */

/** Background tabs beat once a minute: 90 s keeps them (as presence.ts). */
export const CONTROL_TTL_MS = 90_000;
/** How long a holder that said goodbye keeps control: a reload's time. */
export const CONTROL_GRACE_MS = 10_000;
/** Consoles kept per assembly; the least recently seen go first. */
export const MAX_CONSOLES_PER_ASSEMBLY = 50;
/** Assemblies tracked at once; past it, those without consoles go first. */
export const MAX_ASSEMBLIES = 200;

export interface ConsoleKey {
  userId: string;
  /** Random id of the browser tab, generated by the client. */
  tabId: string;
}

export interface ConsoleEntry extends ConsoleKey {
  /** The intranet's name, else the Google one (as in the history). */
  name: string;
  /** First beat of this tab (ms): the oldest console takes control. */
  since: number;
  /** Latest beat (ms). */
  seenAt: number;
  /** When it said goodbye (ms); only a holder in its grace keeps one. */
  leftAt: number | null;
}

/** How control changed: to the first console, on its own, or taken. */
export type ControlChange = "first" | "handed" | "taken";

export interface ControlState {
  holder: ConsoleEntry | null;
  /** Open consoles, the holder's included. */
  consoles: number;
  /** Set when this call changed who holds control. */
  change: ControlChange | null;
  /** The holder before the change, if there was one. */
  previous: ConsoleEntry | null;
  /**
   * The change the caller records, as the new holder: set once per change,
   * on the holder's own call.
   */
  announce: ControlChange | null;
}

interface AssemblyControl {
  consoles: Map<string, ConsoleEntry>;
  holder: string | null;
  /** The latest change, until its holder records it. */
  pending: ControlChange | null;
}

const store = new Map<string, AssemblyControl>();

const keyOf = (key: ConsoleKey) => `${key.userId}\u0000${key.tabId}`;

function alive(entry: ConsoleEntry, now: number): boolean {
  if (now - entry.seenAt > CONTROL_TTL_MS) return false;
  return entry.leftAt === null || now - entry.leftAt <= CONTROL_GRACE_MS;
}

function prune(control: AssemblyControl, now: number): void {
  for (const [key, entry] of control.consoles) {
    if (!alive(entry, now)) control.consoles.delete(key);
  }
}

function stateOf(
  control: AssemblyControl,
  change: ControlChange | null,
  previous: ConsoleEntry | null,
  caller: string | null,
): ControlState {
  let announce: ControlChange | null = null;
  if (control.pending && caller !== null && control.holder === caller) {
    announce = control.pending;
    control.pending = null;
  }
  return {
    holder: control.holder
      ? (control.consoles.get(control.holder) ?? null)
      : null,
    consoles: control.consoles.size,
    change,
    previous,
    announce,
  };
}

/**
 * Gives control to the console open longest when nobody alive holds it:
 * "first" when nobody held it before, "handed" when its holder went.
 */
function settle(
  control: AssemblyControl,
  now: number,
  /** The holder as it was before this call pruned anything. */
  before: ConsoleEntry | null,
): { change: ControlChange | null; previous: ConsoleEntry | null } {
  const holderKey = control.holder;
  const current = holderKey ? control.consoles.get(holderKey) : undefined;
  if (current && alive(current, now)) return { change: null, previous: null };
  const next = [...control.consoles.entries()]
    .filter(([, entry]) => entry.leftAt === null && alive(entry, now))
    .sort((a, b) => a[1].since - b[1].since)[0];
  control.holder = next ? next[0] : null;
  if (!next) {
    control.pending = null;
    return { change: null, previous: null };
  }
  const change: ControlChange = holderKey ? "handed" : "first";
  control.pending = change;
  return { change, previous: before };
}

function controlOf(assemblyId: string, now: number): AssemblyControl {
  let control = store.get(assemblyId);
  if (control) return control;
  if (store.size >= MAX_ASSEMBLIES) {
    for (const [id, entry] of store) {
      prune(entry, now);
      if (entry.consoles.size === 0) store.delete(id);
    }
  }
  control = { consoles: new Map(), holder: null, pending: null };
  store.set(assemblyId, control);
  return control;
}

function touch(
  control: AssemblyControl,
  entry: ConsoleKey & { name: string },
  now: number,
): void {
  const key = keyOf(entry);
  const previous = control.consoles.get(key);
  control.consoles.set(key, {
    userId: entry.userId,
    tabId: entry.tabId,
    name: entry.name,
    since: previous?.since ?? now,
    seenAt: now,
    // Beating again (a reload of the same tab) takes back a goodbye.
    leftAt: null,
  });
  if (control.consoles.size > MAX_CONSOLES_PER_ASSEMBLY) {
    const stale = [...control.consoles.entries()]
      .filter(([other]) => other !== key && other !== control.holder)
      .sort((a, b) => a[1].seenAt - b[1].seenAt)
      .slice(0, control.consoles.size - MAX_CONSOLES_PER_ASSEMBLY);
    for (const [other] of stale) control.consoles.delete(other);
  }
}

/** The holder entry as it is, before anything is pruned. */
const holderOf = (control: AssemblyControl): ConsoleEntry | null =>
  control.holder ? (control.consoles.get(control.holder) ?? null) : null;

/** One beat of an open console; gives control on if nobody alive holds it. */
export function beatConsole(
  assemblyId: string,
  entry: ConsoleKey & { name: string },
  now: number = Date.now(),
): ControlState {
  const control = controlOf(assemblyId, now);
  const before = holderOf(control);
  prune(control, now);
  touch(control, entry, now);
  const { change, previous } = settle(control, now, before);
  return stateOf(control, change, previous, keyOf(entry));
}

/** The console takes control, whoever held it. */
export function takeControl(
  assemblyId: string,
  entry: ConsoleKey & { name: string },
  now: number = Date.now(),
): ControlState {
  const control = controlOf(assemblyId, now);
  const previous = holderOf(control);
  prune(control, now);
  touch(control, entry, now);
  const key = keyOf(entry);
  if (control.holder === key) return stateOf(control, null, null, key);
  control.holder = key;
  control.pending = "taken";
  return stateOf(control, "taken", previous, key);
}

/**
 * The console closes. The holder keeps control for CONTROL_GRACE_MS (a
 * reload of the same tab beats again in time); any other drops out at once.
 */
export function leaveConsole(
  assemblyId: string,
  key: ConsoleKey,
  now: number = Date.now(),
): ControlState {
  const control = store.get(assemblyId);
  if (!control) {
    return {
      holder: null,
      consoles: 0,
      change: null,
      previous: null,
      announce: null,
    };
  }
  const before = holderOf(control);
  const own = keyOf(key);
  const entry = control.consoles.get(own);
  if (entry) {
    if (control.holder === own) entry.leftAt = now;
    else control.consoles.delete(own);
  }
  prune(control, now);
  const { change, previous } = settle(control, now, before);
  // A console that leaves records nothing: whoever receives control does.
  return stateOf(control, change, previous, null);
}

/**
 * Whether the console holds control now. Only reads: a holder gone stale
 * stops controlling at once, and control passes on at the next beat.
 */
export function isController(
  assemblyId: string,
  key: ConsoleKey,
  now: number = Date.now(),
): boolean {
  const control = store.get(assemblyId);
  if (!control || control.holder !== keyOf(key)) return false;
  const entry = control.consoles.get(control.holder);
  return !!entry && alive(entry, now);
}

/** For tests. */
export function resetProjectionControl(): void {
  store.clear();
}
