import { z } from "zod/v4";
import {
  AMENDMENT_KINDS,
  APPROVAL_METHODS,
  DECISION_METHODS,
  MAJORITIES,
  PROPONENT_POSITIONS,
  RELATION_KINDS,
  VOTE_METHODS,
} from "../../constants/domain";
import type {
  AcceptanceBody,
  AdmissionBody,
  AmendmentDraftBody,
  AmendmentUpdateBody,
  OutcomeBody,
  PositionBody,
  PublishAmendmentsBody,
  ReclassifyBody,
  RelationBody,
  TransactionalBody,
  ValidateAmendmentsBody,
  VoteInput,
} from "../../types/api";
import { RECLASSIFIABLE_KINDS } from "../amendmentReclassify";
import { amendmentOpsSchema, normalizeText } from "./content";

/**
 * Request bodies of the amendment API (docs/api.md, "Amendments"). Each
 * schema is checked against its type in shared/types/api.ts below.
 */

export const JUSTIFICATION_MAX_LENGTH = 20_000;
export const NOTE_MAX_LENGTH = 2_000;
export const MAX_AUTHORS = 20;
export const MAX_TRANSACTIONAL_SOURCES = 20;
export const MAX_ADMISSION_BATCH = 500;
const MAX_VOTE_COUNT = 100_000;

/** CUID2 ids as generated by `cuid()` in the schema. */
export const entityIdSchema = z.string().regex(/^[a-z0-9]{20,32}$/);

/** The `updatedAt` echoed back for optimistic locking. */
export const updatedAtSchema = z.iso.datetime({ offset: true });

const noteSchema = z
  .string()
  .max(NOTE_MAX_LENGTH)
  .transform((value) => normalizeText(value).trim())
  .nullable()
  .optional();

const justificationSchema = z
  .string()
  .max(JUSTIFICATION_MAX_LENGTH)
  .transform((value) => normalizeText(value).trim());

const uniqueIds = (max: number, min = 0) =>
  z
    .array(entityIdSchema)
    .min(min)
    .max(max)
    .refine((ids) => new Set(ids).size === ids.length, {
      message: "duplicate_id",
    });

const globalReplaceSchema = z
  .object({
    find: z.string().min(1).max(500),
    replace: z.string().max(500),
  })
  .nullable()
  .optional();

const draftKindSchema = z.enum(
  AMENDMENT_KINDS.filter(
    (
      kind,
    ): kind is Exclude<(typeof AMENDMENT_KINDS)[number], "transactional"> =>
      kind !== "transactional",
  ) as [
    Exclude<(typeof AMENDMENT_KINDS)[number], "transactional">,
    ...Exclude<(typeof AMENDMENT_KINDS)[number], "transactional">[],
  ],
);

const count = z.number().int().min(0).max(MAX_VOTE_COUNT);

export const voteInputSchema = z.object({
  method: z.enum(VOTE_METHODS),
  inFavor: count.optional(),
  against: count.optional(),
  abstentions: count.optional(),
  blank: count.optional(),
  invalid: count.optional(),
  present: count.nullable().optional(),
  majority: z.enum(MAJORITIES).optional(),
  note: noteSchema,
});

const draftFields = {
  kind: draftKindSchema,
  ops: amendmentOpsSchema,
  justification: justificationSchema,
  authorMemberIds: uniqueIds(MAX_AUTHORS).optional(),
  /** Main author among the authors; required when there are several. */
  mainAuthorMemberId: entityIdSchema.nullable().optional(),
  globalReplace: globalReplaceSchema,
  onBehalfOfMemberId: entityIdSchema.nullable().optional(),
};

export const amendmentDraftBodySchema = z.object(draftFields);

export const amendmentUpdateBodySchema = z.object({
  kind: draftFields.kind.optional(),
  ops: draftFields.ops.optional(),
  justification: draftFields.justification.optional(),
  authorMemberIds: draftFields.authorMemberIds,
  mainAuthorMemberId: draftFields.mainAuthorMemberId,
  globalReplace: draftFields.globalReplace,
  onBehalfOfMemberId: draftFields.onBehalfOfMemberId,
  updatedAt: updatedAtSchema,
});

export const transactionalBodySchema = z.object({
  sourceIds: uniqueIds(MAX_TRANSACTIONAL_SOURCES, 1),
  ops: amendmentOpsSchema,
  justification: justificationSchema,
  authorMemberIds: uniqueIds(MAX_AUTHORS).optional(),
  mainAuthorMemberId: entityIdSchema.nullable().optional(),
  submit: z.boolean().optional(),
});

export const admissionBodySchema = z
  .object({
    amendmentIds: uniqueIds(MAX_ADMISSION_BATCH, 1),
    decision: z.enum(["admitted", "inadmissible"]),
    method: z.enum(DECISION_METHODS),
    note: noteSchema,
    vote: voteInputSchema.nullable().optional(),
  })
  .refine((body) => body.method !== "vote" || Boolean(body.vote), {
    message: "vote_required",
    path: ["vote"],
  });

/** POST .../amendments/validate (ValidateAmendmentsBody). */
export const validateAmendmentsBodySchema = z.object({
  amendmentIds: uniqueIds(MAX_ADMISSION_BATCH, 1),
  publish: z.boolean(),
});

/** POST .../amendments/publish (PublishAmendmentsBody). */
export const publishAmendmentsBodySchema = z.object({
  amendmentIds: uniqueIds(MAX_ADMISSION_BATCH, 1),
});

export const positionBodySchema = z.object({
  position: z.enum(PROPONENT_POSITIONS),
  comment: noteSchema,
  /** PositionDto.updatedAt the client saw, null when there was none. */
  positionUpdatedAt: updatedAtSchema.nullable().optional(),
});

export const acceptanceBodySchema = z.object({
  decision: z.enum(["accepted", "rejected"]),
  memberId: entityIdSchema.nullable().optional(),
});

const nonVoteApprovalMethods = APPROVAL_METHODS.filter(
  (method): method is Exclude<(typeof APPROVAL_METHODS)[number], "vote"> =>
    method !== "vote",
) as [
  Exclude<(typeof APPROVAL_METHODS)[number], "vote">,
  ...Exclude<(typeof APPROVAL_METHODS)[number], "vote">[],
];

export const outcomeBodySchema = z.discriminatedUnion("action", [
  z.object({
    action: z.literal("approve"),
    method: z.enum(nonVoteApprovalMethods),
    note: noteSchema,
    updatedAt: updatedAtSchema,
  }),
  z.object({
    action: z.literal("vote"),
    vote: voteInputSchema,
    updatedAt: updatedAtSchema,
  }),
  z.object({
    action: z.literal("withdraw"),
    note: noteSchema,
    updatedAt: updatedAtSchema,
  }),
  z.object({
    action: z.literal("lapse"),
    note: noteSchema,
    updatedAt: updatedAtSchema,
  }),
  z.object({
    action: z.literal("reopen"),
    note: noteSchema,
    updatedAt: updatedAtSchema,
  }),
]);

export const relationBodySchema = z
  .object({
    fromId: entityIdSchema,
    toId: entityIdSchema,
    kind: z.enum(RELATION_KINDS),
    note: noteSchema,
  })
  .refine((body) => body.fromId !== body.toId, {
    message: "same_amendment",
    path: ["toId"],
  });

/** Body of POST .../amendments/[amendment]/reclassify (ReclassifyBody). */
export const reclassifyBodySchema = z.object({
  kind: z.enum(RECLASSIFIABLE_KINDS),
  updatedAt: updatedAtSchema,
});

// Compile-time checks: every parsed body is assignable to its API type.
type Assignable<T, U extends T> = U;
export type _AmendmentSchemaChecks = [
  Assignable<ReclassifyBody, z.output<typeof reclassifyBodySchema>>,
  Assignable<VoteInput, z.output<typeof voteInputSchema>>,
  Assignable<AmendmentDraftBody, z.output<typeof amendmentDraftBodySchema>>,
  Assignable<AmendmentUpdateBody, z.output<typeof amendmentUpdateBodySchema>>,
  Assignable<TransactionalBody, z.output<typeof transactionalBodySchema>>,
  Assignable<AdmissionBody, z.output<typeof admissionBodySchema>>,
  Assignable<
    ValidateAmendmentsBody,
    z.output<typeof validateAmendmentsBodySchema>
  >,
  Assignable<
    PublishAmendmentsBody,
    z.output<typeof publishAmendmentsBodySchema>
  >,
  Assignable<PositionBody, z.output<typeof positionBodySchema>>,
  Assignable<AcceptanceBody, z.output<typeof acceptanceBodySchema>>,
  Assignable<OutcomeBody, z.output<typeof outcomeBodySchema>>,
  Assignable<RelationBody, z.output<typeof relationBodySchema>>,
];
